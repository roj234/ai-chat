registerToolset("Memories", "记忆（也是挂载点 + 提示词）", [], {
	hidden: 'manual',
	systemPrompt,
	depend: ["Files"],
	onActivated(conv) {
		(conv.mnt || (conv.mnt = {}))["memory"] = {
			fs_builtin: true,
			fs_base: "memory",
			fs_name: "长期记忆目录"
		};
		return [];
	},
	onDeactivated(conv) {
		const mnt = conv.mnt;
		if (mnt) delete mnt["memory"];
	}
});
